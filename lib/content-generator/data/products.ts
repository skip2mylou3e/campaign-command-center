// Helper: get products grouped by category
export function getProductsByCategory(): Record<string, Product[]> {
  const grouped: Record<string, Product[]> = {};
  for (const product of products) {
    const key = product.subcategory
      ? `${product.category} - ${product.subcategory}`
      : product.category;
    if (!grouped[key]) grouped[key] = [];
    grouped[key].push(product);
  }
  return grouped;
}

// Helper: get products filtered by region
export function getProductsByRegion(region: string): Product[] {
  return products.filter(p => p.regions.includes(region) || p.regions.includes('Global'));
}
